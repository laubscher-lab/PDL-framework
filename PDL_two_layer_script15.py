for label, (n, edges) in STRUCTURES:
    m = len(edges)
    if m > 15:
        print(f"  {label:>16s} {n:3d} {m:4d} {m-n+1:3d} {'--':>5s} "
              f"{'(not enumerated)':>17s} {gauge_count(n):15d} {'--':>11s}")
        continue
    em = eidx_map(edges)
    tris = triangles_of(n, edges)
    c = m - n + 1
    adm = set()
    for y in itertools.product((1, -1), repeat=m):
        if not all(tri_ok(y, T, em) for T in tris):
            continue
        # sigma is any induced configuration; delta = y * sigma
        for xbits in range(1 << n):
            x = [1 if (xbits >> i) & 1 else -1 for i in range(n)]
            sig = induced(x, edges)
            adm.add(tuple(y[k] * sig[k] for k in range(m)))
    allg = all(factorises(d, n, edges) for d in adm)
    print(f"  {label:>16s} {n:3d} {m:4d} {c:3d} {len(tris):5d} "
          f"{len(adm):17d} {gauge_count(n):15d} {str(allg):>11s}")
print()

print("Q1/Q2 -- Reading B: C2 constrains only the INDUCED signs sigma")
print("-" * 74)
print("  Then y is unconstrained, delta ranges over all 2^m sign patterns,")
print("  and the non-gauge part has dimension c = m - n + 1: the number of")
print("  independent cycles. delta then carries genuine information --")
print("  exactly c bits of it -- and is NOT removable by relabelling.")
print()
print(f"  {'structure':>16s} {'n':>3s} {'m':>4s} {'c':>3s} "
      f"{'all delta 2^m':>14s} {'gauges 2^(n-1)':>15s} "
      f"{'non-gauge 2^c':>14s} {'check':>7s}")
for label, (n, edges) in STRUCTURES:
    m = len(edges)
    if m > 18:
        continue
    c = m - n + 1
    gau = sum(1 for d in itertools.product((1, -1), repeat=m)
              if factorises(d, n, edges))
    ok = (gau == gauge_count(n)) and (2 ** m == gauge_count(n) * 2 ** c)
    print(f"  {label:>16s} {n:3d} {m:4d} {c:3d} {2**m:14d} {gau:15d} "
          f"{2**c:14d} {str(ok):>7s}")
print()
print("  The factorisation 2^m = 2^(n-1) * 2^c is the cyclomatic identity")
print("  again: n-1 gauge dimensions, c observable ones. Under reading B")
print("  the relation layer carries c independent bits that no relabelling")
print("  of entities can remove. On a COMPLETE graph c is large but every")
print("  cycle is triangle-generated, so C2 on y would kill them all --")
print("  which is precisely reading A. The two readings differ exactly by")
print("  whether C2 sees the relation layer.")
print()


