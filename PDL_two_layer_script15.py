def induced(x, edges):
    return tuple(x[u] * x[v] for (u, v) in edges)


def triangles_of(n, edges):
    E = {frozenset(e) for e in edges}
    return [T for T in combinations(range(n), 3)
            if all(frozenset(p) in E for p in combinations(T, 2))]


def eidx_map(edges):
    return {frozenset(e): k for k, e in enumerate(edges)}


def tri_ok(sig, T, em):
    a, b, c = T
    return (sig[em[frozenset((a, b))]] *
            sig[em[frozenset((a, c))]] *
            sig[em[frozenset((b, c))]]) == 1


def cycle_basis(n, edges):
    """Fundamental cycles as edge-index sets, via a spanning tree."""
    parent = list(range(n))

    def find(a):
        while parent[a] != a:
            parent[a] = parent[parent[a]]
            a = parent[a]
        return a

    tree, extra = [], []
    adj = {i: [] for i in range(n)}
    for k, (u, v) in enumerate(edges):
        ru, rv = find(u), find(v)
        if ru != rv:
            parent[ru] = rv
            tree.append(k)
            adj[u].append((v, k))
            adj[v].append((u, k))
        else:
            extra.append(k)

    def path(a, b):
        seen, st = {a: []}, [a]
        while st:
            z = st.pop()
            if z == b:
                return seen[z]
            for (w, k) in adj[z]:
                if w not in seen:
                    seen[w] = seen[z] + [k]
                    st.append(w)
        return []

    return [set(path(edges[k][0], edges[k][1]) + [k]) for k in extra]


def factorises(delta, n, edges):
    """Is delta of the form z_i z_j ? (Harary: product +1 on every cycle)"""
    for cyc in cycle_basis(n, edges):
        p = 1
        for k in cyc:
            p *= delta[k]
        if p != 1:
            return False
    return True


def gauge_count(n):
    return 2 ** (n - 1)


