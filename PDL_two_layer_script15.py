# Q3 -- the beat: two desynchronised pulsations
# ============================================================
print("Q3 -- Two layers pulsing with different phase bipartitions")
print("-" * 74)
print("  Entity layer pulses by switching a vertex subset S (D68 Thm 6.3).")
print("  Relation layer pulses by its own involution: flip the y of every")
print("  edge in a fixed edge subset F. Both are involutions, so each")
print("  alone has period 2. The question is what delta does.")
print()


def beat(n, edges, S, F, steps=8):
    m = len(edges)
    x = [1] * n
    y = [1] * m
    out = []
    for t in range(steps):
        sig = induced(x, edges)
        out.append(tuple(y[k] * sig[k] for k in range(m)))
        x = [(-x[i] if i in S else x[i]) for i in range(n)]
        y = [(-y[k] if k in F else y[k]) for k in range(m)]
    return out


def exact_period(seq):
    L = len(seq)
    for T in range(1, L // 2 + 1):
        if all(seq[t] == seq[t + T] for t in range(L - T)):
            return T
    return None


for label, (n, edges) in STRUCTURES[:6]:
    m = len(edges)
    if m > 15 or n > 6:
        print(f"  {label:>16s}: skipped (too large for exhaustive beat)")
        continue
    em = eidx_map(edges)
    periods = {}
    nonfixed = 0
    total = 0
    for Sb in range(1 << n):
        S = {i for i in range(n) if (Sb >> i) & 1}
        for Fb in range(min(1 << m, 256)):
            F = {k for k in range(m) if (Fb >> k) & 1}
            seq = beat(n, edges, S, F)
            T = exact_period(seq)
            total += 1
            periods[T] = periods.get(T, 0) + 1
            if len(set(seq)) > 1:
                nonfixed += 1
    print(f"  {label:>16s}: {total} (S,F) pairs sampled; "
          f"non-constant delta in {nonfixed} "
          f"({100.0*nonfixed/total:.1f}%)")
    print(f"  {'':>16s}  period spectrum: " +
          ", ".join(f"{k}:{v}" for k, v in sorted(periods.items(),
                                                  key=lambda z: (z[0] is None, z[0]))))
print()
print("  A delta that is non-constant for most (S,F) pairs means the two")
print("  layers genuinely beat against each other. But note carefully: a")
print("  PERIOD-2 beat is still a closed cycle, not a motor. What would")
print("  matter is a period LONGER than 2, since C1 admits only 2-cycles")
print("  on a single layer -- a longer period could only come from the")
print("  two layers together.")
print()


