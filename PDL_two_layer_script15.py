print("Q3b -- Periods longer than 2: the only place a motor could hide")
print("-" * 74)
for label, (n, edges) in STRUCTURES[:6]:
    m = len(edges)
    if m > 15 or n > 6:
        print(f"  {label:>16s}: skipped")
        continue
    long_p = {}
    for Sb in range(1 << n):
        S = {i for i in range(n) if (Sb >> i) & 1}
        for Fb in range(min(1 << m, 256)):
            F = {k for k in range(m) if (Fb >> k) & 1}
            T = exact_period(beat(n, edges, S, F))
            if T is not None and T > 2:
                long_p[T] = long_p.get(T, 0) + 1
    print(f"  {label:>16s}: periods > 2 -> "
          f"{long_p if long_p else 'NONE'}")
print()
print("  If no period exceeds 2 anywhere, the two-layer construction adds")
print("  no dynamics: both involutions commute and the pair is still an")
print("  involution. That would be a clean negative result and would close")
print("  the beat idea, leaving the two-layer picture as a description")
print("  rather than a mechanism.")
