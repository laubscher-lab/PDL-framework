# PDL_two_layer_script15.py
# ============================================================
# Two layers: entity states and relation states.
# Is the disagreement a gauge, or a genuine object?
#
# ############################################################
# TERMINOLOGY (corpus rule, non-negotiable)
#   Valence cores are K_24 and K_28: complete graphs on ENTITIES.
#   The literal K_4 of D61 denotes the electron closure only.
#   Composite nucleon closures (K_nuc) are not treated here.
#   Small complete graphs below are abstract test structures, not
#   electron closures.
# ############################################################
#
# WHERE THIS COMES FROM
#   Everything computed in this session has lived on ONE layer: the
#   entity states x_i = +-1, with relations entering only as the
#   induced product sigma_ij = x_i x_j. That was deliberate --- D68
#   showed the axioms are blind to the phase, which lives on the
#   entities. But it also means relations were never treated as
#   objects in their own right.
#
#   D42 does treat them as objects: the proton relations p_k appear
#   as VERTICES of cross-triangles. A relation at one level is an
#   entity at the next. The corpus therefore already performs the
#   level shift, without naming it.
#
# THE CONSTRUCTION
#   Give each edge its own state y_ij, independent of the entities,
#   and define the DISAGREEMENT
#        delta_ij = y_ij * sigma_ij,   sigma_ij = x_i x_j.
#   delta = +1: the relation agrees with its endpoints; -1: it does
#   not. delta is invariant under the global inversion x -> -x (both
#   sigma and y are), so it is legitimate on relational data. It is
#   NOT switching-invariant, so it sees what C4 cannot. And it is
#   defined by a comparison, not by a minimisation --- the first
#   object of this session whose definition does not close on an
#   extremum.
#
# THE DANGER, and why this script exists
#   If delta always factorises as delta_ij = z_i z_j for some vertex
#   assignment z, then setting x'_i = x_i z_i makes the disagreement
#   vanish identically: it is a pure GAUGE, carrying no information,
#   and the two-layer picture collapses back to the one-layer one.
#   That is the same obstacle every construction hit this session,
#   and it is the FIRST thing tested below.
#
#   Whether delta can factorise is a question about cycles, not
#   about size: delta factorises iff its product around every cycle
#   is +1 (Harary). On a COMPLETE graph all cycles are generated by
#   triangles, so constraining triangles constrains everything and
#   delta is very likely a gauge. On a SPARSE mesh there are long
#   cycles no triangle controls, and delta may survive. The sea is
#   sparse. Both regimes are therefore tested, and a negative result
#   on complete graphs alone would NOT close the question.
#
# THE THREE QUESTIONS
#   Q1  Which layer does C2 constrain --- the induced signs sigma,
#       or the proper signs y? Under each reading, what is the space
#       of admissible delta?
#   Q2  Is delta always of the form z_i z_j (a gauge), or can it be
#       cohomologically non-trivial? Measured as: the number of
#       admissible delta, versus the 2^(n-1) that are gauges.
#   Q3  If delta survives, do two DESYNCHRONISED pulsations (one per
#       layer) leave it without a fixed point? A beat has no fixed
#       point; a common minimum does. This is where a motor would
#       have to come from.
#
# PREDICTION, recorded before running
#   On complete graphs delta is expected to be a pure gauge under
#   the reading "C2 constrains y", because triangles generate the
#   cycle space. On sparse meshes with independent cycles, the
#   number of admissible delta should exceed the number of gauges
#   by exactly a factor 2^c with c = m - n + 1 the cyclomatic
#   number, IF C2 constrains only sigma. Any departure from this is
#   the result.
#
# Exact integer arithmetic. Standard library only.
#
# Author: Cedric Laubscher
# Date:   August 2026
# ============================================================

