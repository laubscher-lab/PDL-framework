# Test structures
# ============================================================

def K(n):
    return n, [(i, j) for i in range(n) for j in range(i + 1, n)]


def cycle(n):
    return n, [(i, (i + 1) % n) for i in range(n)]


def torus(a, b):
    idx = lambda i, j: (i % a) * b + (j % b)
    e = set()
    for i in range(a):
        for j in range(b):
            e.add(tuple(sorted((idx(i, j), idx(i, j + 1)))))
            e.add(tuple(sorted((idx(i, j), idx(i + 1, j)))))
    return a * b, sorted(e)


def annulus(L, h=2):
    idx = lambda i, j: j * L + i
    e = set()
    for j in range(h):
        for i in range(L):
            e.add(tuple(sorted((idx(i, j), idx((i + 1) % L, j)))))
            if j + 1 < h:
                e.add(tuple(sorted((idx(i, j), idx(i, j + 1)))))
    return L * h, sorted(e)


STRUCTURES = [
    ("K_4  (complete)", K(4)),
    ("K_5  (complete)", K(5)),
    ("K_6  (complete)", K(6)),
    ("C_5  (sparse)", cycle(5)),
    ("C_6  (sparse)", cycle(6)),
    ("C_3xC_3 torus", torus(3, 3)),
    ("annulus L=4", annulus(4, 2)),
    ("annulus L=5", annulus(5, 2)),
    ("annulus L=6", annulus(6, 2)),
]


